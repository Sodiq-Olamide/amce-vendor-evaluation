# Load environment variables from .env or env.txt if available
env_candidates = [
    BASE_DIR / '.env',
    BASE_DIR.parent / '.env',
    BASE_DIR / 'env.txt',
    BASE_DIR.parent / 'env.txt',
]
for env_path in env_candidates:
    if env_path.exists():
        with open(env_path, 'r', encoding='utf-8', errors='ignore') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('#') and '=' in line:
                    k, v = line.split('=', 1)
                    k = k.strip()
                    v = v.strip().strip('"').strip("'")
                    if k and k not in os.environ:
                        os.environ[k] = v

